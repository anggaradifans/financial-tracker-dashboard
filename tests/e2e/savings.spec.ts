import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Asia/Jakarta' })

test('savings report separates currencies, drills into history, and reflects edits and deletions', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-04-10T15:00:00+07:00'))
  const user = { id: 'savings-owner', email: 'savings@example.test', aud: 'authenticated', role: 'authenticated', user_metadata: {} }
  const category = { id: 'cash-flow', name: 'Cash flow', allowed_type: 'both' }
  const account = { id: 'checking', name: 'Checking', currency: 'IDR' }
  const makeTx = (id: string, type: string, amount: number, day: string, currency = 'IDR') => ({ id, type, amount, currency, occurred_at: `${day}T05:00:00Z`, created_at: `${day}T05:00:00Z`, description: id, category_id: category.id, account_id: account.id, metadata: {}, categories: category, accounts: account, user_id: user.id, deleted_at: null })
  let rows = [
    makeTx('Salary', 'income', 1000, '2026-04-01'), makeTx('Spending', 'outcome', 400, '2026-04-02'),
    makeTx('Refund', 'income', 100, '2026-04-03'), makeTx('Owned transfer out', 'transfer_out', 800, '2026-04-04'),
    makeTx('Owned transfer in', 'transfer_in', 800, '2026-04-04'), makeTx('Dollar income', 'income', 50, '2026-04-02', 'USD'),
    makeTx('March expense', 'outcome', 200, '2026-03-25'), makeTx('February expense', 'outcome', 100, '2026-02-12'),
    makeTx('March refund', 'income', 20, '2026-03-10'), makeTx('January income', 'income', 1000, '2026-01-02'),
  ]
  const writes: string[] = []
  let failHistory = true
  let historyLoads = 0
  await page.route('**/auth/v1/**', route => route.fulfill({ json: { access_token: 'test-access-token', refresh_token: 'test-refresh-token', token_type: 'bearer', expires_in: 3600, user } }))
  await page.route('**/rest/v1/**', async route => {
    const url = new URL(route.request().url())
    if (route.request().method() !== 'GET') writes.push(url.pathname)
    if (url.pathname.endsWith('/transactions')) {
      if (url.searchParams.get('offset') === '0') historyLoads++
      if (url.searchParams.get('offset') === '0' && failHistory) {
        failHistory = false
        return route.fulfill({ status: 503, body: 'History temporarily unavailable' })
      }
      if (route.request().method() === 'PATCH') {
        const id = url.searchParams.get('id')?.replace('eq.', '')
        rows = rows.map(row => row.id === id ? { ...row, ...route.request().postDataJSON() } : row)
        return route.fulfill({ json: rows.filter(row => row.id === id) })
      }
      let filtered = rows.filter(row => !row.deleted_at)
      for (const bound of url.searchParams.getAll('occurred_at')) {
        if (bound.startsWith('gte.')) filtered = filtered.filter(row => new Date(row.occurred_at) >= new Date(bound.slice(4)))
        if (bound.startsWith('lte.')) filtered = filtered.filter(row => new Date(row.occurred_at) <= new Date(bound.slice(4)))
      }
      return route.fulfill({ json: filtered })
    }
    return route.fulfill({ json: url.pathname.endsWith('/accounts') ? [account] : url.pathname.endsWith('/categories') ? [category] : [] })
  })
  await page.goto('/')
  await page.getByLabel('Email Address').fill(user.email)
  await page.getByLabel('Password', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Could not load savings history')
  await page.getByRole('button', { name: 'Retry savings history' }).click()
  const idr = page.getByRole('region', { name: 'IDR savings', exact: true })
  const usd = page.getByRole('region', { name: 'USD savings', exact: true })
  const selected = idr.locator('div').filter({ has: page.getByRole('heading', { name: /^Selected period:/ }) }).first()
  await expect(idr).toBeVisible()
  await expect(selected.locator('dd').nth(2)).toContainText('700')
  await expect(usd).toContainText('$50.00')
  await expect(idr).toContainText('Partial period')
  const drill = idr.locator('summary').filter({ hasText: 'Selected-period transactions' })
  await expect(drill).toHaveText('Selected-period transactions (3)')
  await drill.press('Enter')
  await expect(selected.getByText('Refund', { exact: true })).toBeVisible()
  await expect(idr.getByText('Owned transfer out', { exact: true })).toHaveCount(0)
  await idr.getByText('Monthly transaction history', { exact: true }).click()
  await idr.locator('summary').filter({ hasText: 'March 2026' }).click()
  await expect(idr).toContainText('Unavailable')

  const analytics = page.getByRole('navigation', { name: 'Analytics subsections' })
  const cashFlowLink = analytics.getByRole('link', { name: 'Cash flow' })
  const spendingLink = analytics.getByRole('link', { name: 'Spending' })
  const previewLink = analytics.getByRole('link', { name: 'Savings preview' })
  const comparison = page.getByRole('region', { name: 'Spending by category' })
  const opportunities = page.getByRole('region', { name: 'Savings preview' })
  await expect(cashFlowLink).toHaveAttribute('aria-current', 'page')
  await expect(comparison).toHaveCount(0)
  await expect(opportunities).toHaveCount(0)
  await spendingLink.click()
  await expect(comparison.getByText('+100%', { exact: true })).toBeVisible()
  await expect(idr).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Custom Range' })).toBeVisible()
  await comparison.locator('summary').filter({ hasText: 'Transactions for Cash flow' }).press('Enter')
  await expect(comparison.getByText('March expense', { exact: true })).toBeVisible()
  await comparison.getByRole('link', { name: 'Preview a reduction for Cash flow' }).click()
  await expect(page).toHaveURL(/\/dashboard\/analytics\/savings-preview$/)
  await expect(previewLink).toBeFocused()
  await expect(previewLink).toHaveAttribute('aria-current', 'page')
  await expect(opportunities.getByRole('checkbox', { name: 'Include Cash flow' })).toBeChecked()
  await expect(page.getByRole('button', { name: 'Custom Range' })).toHaveCount(0)
  await expect(comparison).toHaveCount(0)
  expect(historyLoads).toBe(2)
  await opportunities.getByRole('textbox', { name: 'Reduction (%)' }).fill('10')
  await expect(opportunities.getByText(/^Additional savings per year:/)).toContainText('180.00')
  await expect(opportunities.getByText(/^Monthly spending target:/)).toContainText('135.00')
  await opportunities.getByText('Adjust baseline', { exact: true }).click()
  await opportunities.locator('summary').filter({ hasText: 'Confirm refunds' }).click()
  await opportunities.getByLabel('Refund credit').selectOption('March refund')
  await opportunities.getByLabel('Original purchase').selectOption('February expense')
  await opportunities.getByRole('button', { name: 'Apply refund' }).click()
  await expect(opportunities.getByText(/^Additional savings per year:/)).toContainText('168.00')
  await opportunities.locator('summary').filter({ hasText: 'Exclude unusual purchases' }).click()
  const excludeMarch = opportunities.getByRole('checkbox', { name: /Exclude .*March expense/ })
  await excludeMarch.check()
  await expect(opportunities.getByText(/^Additional savings per year:/)).toContainText('48.00')
  await excludeMarch.uncheck()
  await opportunities.locator('summary').filter({ hasText: 'Baseline months' }).click()
  const excludeMonth = opportunities.getByRole('checkbox', { name: 'Mark 2026-02 incomplete' })
  await excludeMonth.check()
  await expect(opportunities.getByText(/Include at least two completed months/)).toBeVisible()
  await excludeMonth.uncheck()
  await opportunities.getByRole('checkbox', { name: 'Mark Cash flow essential' }).check()
  await expect(opportunities.getByRole('checkbox', { name: 'Include Cash flow' })).toBeDisabled()
  await opportunities.getByRole('checkbox', { name: 'Mark Cash flow essential' }).uncheck()
  await opportunities.getByRole('checkbox', { name: 'Include Cash flow' }).check()
  await opportunities.getByLabel('Spending currency').selectOption('USD')
  await expect(opportunities.getByText(/^Additional savings per year:/)).toHaveCount(0)
  await opportunities.getByLabel('Spending currency').selectOption('IDR')
  await expect(opportunities.getByText(/^Additional savings per year:/)).toContainText('168.00')
  await cashFlowLink.click()
  await expect(selected.locator('dd').nth(2)).toContainText('700')
  expect(writes).toEqual([])

  await page.getByRole('link', { name: 'Transactions', exact: true }).click()
  const spending = page.getByRole('row').filter({ hasText: 'Spending' })
  await spending.getByTitle('Edit', { exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Edit Transaction' })
  await dialog.getByLabel('Amount', { exact: true }).fill('600')
  await dialog.getByRole('button', { name: /update transaction/i }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await expect(selected.locator('dd').nth(2)).toContainText('500')
  await previewLink.click()
  await expect(opportunities.getByText(/^Additional savings per year:/)).toContainText('168.00')
  await spendingLink.click()
  await expect(comparison.getByText('+200%', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Transactions', exact: true }).click()
  await page.getByRole('row').filter({ hasText: 'Refund' }).getByTitle('Delete transaction').click()
  await page.getByRole('button', { name: 'Delete', exact: true }).filter({ visible: true }).click()
  await page.getByRole('link', { name: 'Analytics', exact: true }).click()
  await expect(drill).toHaveText('Selected-period transactions (2)')
  await expect(selected.locator('dd').nth(2)).toContainText('400')
})

test('demo savings stays usable on mobile and in both themes', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-04-10T15:00:00+07:00'))
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/demo/analytics')
  await expect(page.getByRole('heading', { name: 'Cash-flow savings', exact: true })).toBeVisible()
  await page.getByText('Monthly transaction history', { exact: true }).click()
  await expect(page.locator('summary').filter({ hasText: 'Incomplete history' }).first()).toBeVisible()
  const drill = page.locator('summary').filter({ hasText: 'Selected-period transactions' })
  await drill.press('Enter')
  await expect(page.getByText('Monthly Salary', { exact: true }).first()).toBeVisible()
  const analytics = page.getByRole('navigation', { name: 'Analytics subsections' })
  const opportunities = page.getByRole('region', { name: 'Savings preview' })
  await analytics.getByRole('link', { name: 'Savings preview' }).click()
  await opportunities.locator('summary').filter({ hasText: 'Baseline months' }).click()
  await expect(opportunities.getByText(/Check at least one category to see its spending/)).toBeVisible()
  await expect(opportunities.getByText(/in selected purchases/)).toHaveCount(0)
  await opportunities.getByRole('checkbox', { name: 'Include Food & Dining' }).check()
  await expect(opportunities.getByText(/in selected purchases/)).toHaveCount(2)
  await expect(opportunities.getByText(/Enter a reduction above/)).toBeVisible()
  await opportunities.getByRole('textbox', { name: 'Reduction (%)' }).fill('10')
  await expect(opportunities.getByRole('heading', { name: 'Estimated additional savings' })).toBeVisible()
  for (const theme of ['dark', 'light']) {
    await page.getByRole('button', { name: `Switch to ${theme} mode` }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(opportunities.getByLabel('Baseline start month')).toHaveCSS('color-scheme', theme)
  }
  await opportunities.screenshot({ path: '/tmp/spending-opportunities-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await opportunities.screenshot({ path: '/tmp/spending-opportunities-desktop.png' })
  await analytics.getByRole('link', { name: 'Spending' }).click()
  await page.getByRole('button', { name: 'Custom Range' }).click()
  await page.getByLabel('Start Date', { exact: true }).fill('2026-03-01')
  await page.getByLabel('End Date', { exact: true }).fill('2026-03-31')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  const comparison = page.getByRole('region', { name: 'Spending by category' })
  await expect(comparison.getByText(/Mar 1, 2026 to Mar 31, 2026/)).toBeVisible()
  await page.goBack()
  await expect(opportunities.getByLabel('Baseline start month')).toHaveValue('2026-01')
  await expect(opportunities.getByRole('textbox', { name: 'Reduction (%)' })).toHaveValue('10')
  await analytics.getByRole('link', { name: 'Cash flow' }).click()
  await expect(page.getByRole('heading', { name: /^Selected period:/ })).toContainText('Mar 1, 2026')
  await page.getByRole('link', { name: 'Goal contributions', exact: true }).click()
  await expect(page).toHaveURL(/\/demo\/goals$/)
})

